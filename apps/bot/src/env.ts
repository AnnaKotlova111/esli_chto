import { existsSync } from 'node:fs';

// Локальный запуск (npm start) читает .env из текущей папки; переменные окружения (Docker, хостинг) важнее файла.
// Отдельный модуль, который server.ts импортирует первым: модули выполняются в порядке импорта,
// поэтому .env загружается раньше, чем tls.ts и остальные модули прочитают настройки.
if (existsSync('.env')) process.loadEnvFile('.env');
