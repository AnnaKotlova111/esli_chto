import type { Outcome, Question } from '../types';

/**
 * Помощники для компактного описания правил.
 * В строках можно использовать подстановки формы управления домом:
 * {M} {M_gen} {M_dat} {M_acc} {M_ins} – «управляющая организация» / «ТСЖ» / «ЖСК».
 */

type OutcomeInput = Pick<Outcome, 'responsible' | 'headline' | 'why' | 'steps' | 'norms'> &
  Partial<Pick<Outcome, 'certainty' | 'basis' | 'note' | 'request'>>;

export const out = (o: OutcomeInput): Outcome => ({
  certainty: 'clear',
  basis: 'norm',
  ...o,
});

export const ask = (
  question: string,
  options: { label: string; next: Outcome | Question }[],
  hint?: string,
): Question => ({ ask: question, hint, options });

export const opt = (label: string, next: Outcome | Question) => ({ label, next });

