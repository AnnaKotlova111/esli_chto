import { describe, expect, it } from 'vitest';
import { emphasize } from '../src';

const strong = (s: string) => emphasize(s).filter((p) => p.strong).map((p) => p.text);

describe('выделение главного в тексте', () => {
  it('телефоны и экстренные номера', () => {
    expect(strong('Позвоните 112, при запахе газа – 104.')).toEqual(['112', '104']);
    expect(strong('Диспетчерская: +7 (493) 542-34-73 или 8 (800) 350-42-12')).toEqual(['+7 (493) 542-34-73', '8 (800) 350-42-12']);
  });

  it('ссылки на пункты норм и другие числа не выделяются', () => {
    expect(strong('ПП № 491, п. 10; № 104; 1120 рублей; квартира 104а')).toEqual([]);
  });

  it('запреты – в начале предложения и после запятой', () => {
    expect(strong('Не заходите в помещение с паром. Уведите людей, не наступайте в горячую воду.')).toEqual([
      'Не заходите в помещение с паром',
      'не наступайте в горячую воду',
    ]);
    expect(strong('Если это не опасно, перекройте кран')).toEqual([]);
  });

  it('текст собирается обратно без потерь', () => {
    const s = 'Не трогайте провода, звоните 112 или +7 (49354) 2-44-72.';
    expect(emphasize(s).map((p) => p.text).join('')).toBe(s);
  });
});
